"""Gera dados Go estáticos a partir do menu.xml, sem parser XML no aplicativo."""
import argparse
import hashlib
import json
import re
from pathlib import Path
import xml.etree.ElementTree as ET

# ROOT ancora os caminhos no aplicativo.
ROOT = Path(__file__).resolve().parents[1]
# SOURCE conserva bytes ISO-8859-1 e comentários originais.
SOURCE = ROOT.parents[1] / "material-legado/menu/menu.xml"
# TARGET contém os dados incorporados à fábrica tipada.
TARGET = ROOT / "internal/catalog/menu_legacy_generated.go"


def generate():
    """Preserva ordem, espaços e metadados; ignora itens comentados."""
    # source fornece o hash e a árvore ativa da referência original.
    source = SOURCE.read_bytes()
    # root exige a única raiz Principal.
    root = ET.fromstring(source)
    if root.tag != "menuXml" or len(root) != 1:
        raise ValueError("Estrutura de menu.xml inesperada")
    # fields associa os seis atributos literais, sem interpretar movimentos.
    fields = {"nome": "Name", "tituloPrincipal": "Title", "codigoMovimento": "MovementCode",
              "opcao": "MovementOption", "nomeMovimento": "MovementName", "atalho": "Shortcut"}
    # lines produz fonte Go determinística.
    lines = ["// Code generated by scripts/import_legacy_menu.py; DO NOT EDIT.",
             "// Fonte: material-legado/menu/menu.xml; SHA-256 " + hashlib.sha256(source).hexdigest(),
             "package catalog", "", "// legacyMenuSource conserva literais, ordem e descendentes ativos do XML.",
             "var legacyMenuSource = legacyMenuNode{"]

    def append_node(node, depth):
        """Escreve cada atributo e descendente ativo na ordem original."""
        # indent mantém a estrutura do literal Go.
        indent = "\t" * depth
        if node.tag != "itemMenuXml" or set(node.attrib) - fields.keys():
            raise ValueError("Elemento/atributo de menu não suportado")
        # attribute e field conservam os valores sem trim ou normalização.
        for attribute, field in fields.items():
            if attribute in node.attrib:
                lines.append(indent + field + ": " + json.dumps(node.attrib[attribute], ensure_ascii=False) + ",")
        if len(node):
            lines.append(indent + "Children: []legacyMenuNode{")
            # child conserva os descendentes; comentários não se tornam itens.
            for child in node:
                lines.append(indent + "\t{")
                append_node(child, depth + 2)
                lines.append(indent + "\t},")
            lines.append(indent + "},")

    append_node(root[0], 1)
    lines.extend(["}", ""])
    return "\n".join(lines)


def main():
    """Regenera ou confere dados, sem modificar o XML original."""
    # parser expõe a verificação somente leitura usada pelo build.
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    # arguments e expected selecionam o modo e o fonte esperado.
    arguments = parser.parse_args()
    expected = generate()
    if arguments.check:
        # actual normaliza apenas alinhamento Go de campos, nunca literais XML.
        actual = TARGET.read_text(encoding="utf-8")
        normalize = lambda value: re.sub(r"(?m)^(\s*[A-Za-z]+:)\s+", r"\1 ", value)
        if normalize(actual) != normalize(expected):
            raise SystemExit("Menu divergente; execute scripts/import_legacy_menu.py")
    else:
        TARGET.write_text(expected, encoding="utf-8", newline="\n")
    print("Menu XML: árvore estática íntegra (ordem, literais e itens ativos).")


if __name__ == "__main__":
    main()
